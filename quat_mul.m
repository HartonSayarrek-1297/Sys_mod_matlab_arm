function p3 = quat_mul(p1, p2) % but nothing to comment there.
    p3(1) = p1(1)*p2(1) - p1(2)*p2(2) - p1(3)*p2(3) - p1(4)*p2(4);
    p3(2) = p1(1)*p2(2) + p1(2)*p2(1) + p1(3)*p2(4) - p1(4)*p2(3);
    p3(3) = p1(1)*p2(3) + p1(3)*p2(1) + p1(4)*p2(2) - p1(2)*p2(4);
	p3(4) = p1(1)*p2(4) + p1(4)*p2(1) + p1(2)*p2(3) - p1(3)*p2(2);
end